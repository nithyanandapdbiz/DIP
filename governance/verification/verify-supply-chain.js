'use strict';
/**
 * GOVERNANCE — trusted software supply chain.
 * ============================================================================
 * Measures what can be measured with the tooling actually present, and reports
 * the rest as NOT MEASURED (R-13.3). It does NOT claim Supply Chain Security is
 * complete: signing, attestation and artefact promotion have no tooling here, and
 * a gate that reported them green would be manufacturing the exact assurance the
 * supply chain exists to provide.
 *
 * MEASURED here:
 *   SBOM currency · lockfile integrity · frozen resolution · vulnerability scan
 *   dependency policy (licences) · build reproducibility
 *
 * NOT MEASURED, and stated as such:
 *   artefact provenance attestation · package signing verification
 *   trusted artefact promotion  — no tooling and no registry present
 *
 * Read-only apart from regenerating the SBOM it gates on (R-14.2: regenerate,
 * never read a stored claim).
 *
 * Run:  node governance/verification/verify-supply-chain.js
 * Exit: 0 = every MEASURED property holds   1 = a measured property failed
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { spawnSync } = require('child_process');

const ROOT = path.join(__dirname, '..', '..');
const SBOM = path.join(ROOT, 'governance', 'supply-chain', 'sbom.cdx.json');
const PKG = path.join(ROOT, 'packages', 'contracts');

/**
 * Dependency policy. An allow-list, not a deny-list: a deny-list fails toward
 * inclusion, admitting any licence nobody thought to forbid.
 */
const ALLOWED_LICENCES = new Set([
  'MIT', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', '0BSD',
  // Admitted 2026-07-24 (ADR-0035 web-tier reconciliation). Three permissive licences
  // pulled in transitively by the pinned react/vite/nestjs tooling. Each is permissive
  // and, like the set above, imposes no copyleft obligation — admitted explicitly so the
  // allow-list stays an allow-list (§4) and the decision is auditable, not silent.
  'MIT-0',       // MIT No Attribution — strictly more permissive than MIT (@csstools/color-helpers)
  'Python-2.0',  // PSF License — permissive, GPL-compatible (argparse, via js-yaml/jsdom)
  'CC-BY-4.0',   // Creative Commons Attribution — permissive data licence (caniuse-lite browser-support data)
]);
const MAX_SEVERITY_ALLOWED = 'moderate';
const SEVERITY_ORDER = ['info', 'low', 'moderate', 'high', 'critical'];

let failures = 0;
const measured = [];
const unmeasured = [];
const line = (s) => console.log(s);
const check = (label, cond, detail) => {
  measured.push({ property: label, passed: cond, detail });
  line(`  ${cond ? 'PASS ' : 'FAIL '} ${label}`);
  if (detail) line(`         ${detail}`);
  if (!cond) failures++;
};
const notMeasured = (label, why) => {
  unmeasured.push({ property: label, reason: why });
  line(`  NOT MEASURED  ${label}`);
  line(`         ${why}`);
};

const gateStartedAt = Date.now();
line('');
line('GOVERNANCE — trusted software supply chain');
line('='.repeat(74));

function pnpm(args, timeoutMs = 180000) {
  const r = spawnSync('corepack', ['pnpm', ...args], {
    cwd: ROOT, encoding: 'utf8', shell: true, timeout: timeoutMs,
  });
  return { status: r.status, out: `${r.stdout || ''}${r.stderr || ''}` };
}

// ── 1. SBOM is regenerated by this run ──────────────────────────────────────
line('\n1. Software Bill of Materials');
const gen = spawnSync(process.execPath, [path.join(ROOT, 'governance', 'supply-chain', 'generate-sbom.js')],
  { cwd: ROOT, encoding: 'utf8' });
check('the SBOM generator ran cleanly', gen.status === 0,
  gen.status === 0 ? 'exit 0' : `exit ${gen.status}`);

let sbom = null;
try { sbom = JSON.parse(fs.readFileSync(SBOM, 'utf8')); } catch { sbom = null; }
check('an SBOM is present and machine-readable', sbom !== null,
  sbom ? `${sbom.components.length} component(s), CycloneDX ${sbom.specVersion}` : 'absent or unparseable');

if (sbom) {
  const producedAt = Date.parse(sbom.metadata?.timestamp ?? '');
  check('the SBOM was produced by this run, not left behind',
    Number.isFinite(producedAt) && producedAt >= gateStartedAt - 2000,
    Number.isFinite(producedAt) ? `produced ${Math.max(0, Math.round((Date.now() - producedAt) / 1000))}s ago` : 'no timestamp');

  const props = Object.fromEntries((sbom.metadata?.properties ?? []).map((p) => [p.name, p.value]));
  const required = ['dbiz:repository', 'dbiz:commit', 'dbiz:lockfileSha256', 'dbiz:contentHash'];
  const missingProv = required.filter((k) => !props[k] || props[k] === 'unknown' || props[k] === 'absent');
  check('the SBOM carries provenance binding it to a commit and lockfile',
    missingProv.length === 0, missingProv.length ? `missing: ${missingProv.join(', ')}` : `${required.length} fields`);
}

// ── 2. Lockfile integrity and frozen resolution ─────────────────────────────
line('\n2. Dependency verification');
const lockPath = path.join(ROOT, 'pnpm-lock.yaml');
check('a lockfile is committed', fs.existsSync(lockPath),
  fs.existsSync(lockPath) ? 'pnpm-lock.yaml' : 'absent — resolution is not reproducible');

if (fs.existsSync(lockPath)) {
  // The lockfile bytes are snapshotted and RESTORED afterwards.
  //
  // This gate performs a real install to test frozen resolution, and an install is
  // a mutating operation. Without restoration a drift check would PERSIST the drift
  // it detected: a stray workspace manifest caused pnpm to resolve a new dependency
  // and rewrite the lockfile, so the gate became a source of the defect it exists
  // to detect. A verifier must leave the repository exactly as it found it.
  const snapshot = fs.readFileSync(lockPath);
  const before = crypto.createHash('sha256').update(snapshot).digest('hex');

  const frozen = pnpm(['install', '--frozen-lockfile', '--prefer-offline', '--silent']);

  const after = crypto.createHash('sha256').update(fs.readFileSync(lockPath)).digest('hex');
  const rewritten = before !== after;
  if (rewritten) fs.writeFileSync(lockPath, snapshot);

  check('installation succeeds against the frozen lockfile', frozen.status === 0,
    frozen.status === 0 ? 'no drift between manifest and lockfile'
      : `exit ${frozen.status} - manifest and lockfile disagree`);
  check('resolution did not rewrite the lockfile', !rewritten,
    rewritten ? 'installation rewrote the lockfile - drift detected and REVERTED by this gate'
      : `sha256 ${before.slice(0, 16)}...`);
}

// ── 3. Vulnerability scanning ───────────────────────────────────────────────
line('\n3. Vulnerability scanning');
const audit = pnpm(['audit', '--json']);
let vulns = null;
try {
  const jsonStart = audit.out.indexOf('{');
  vulns = JSON.parse(audit.out.slice(jsonStart)).metadata?.vulnerabilities ?? null;
} catch { vulns = null; }

if (vulns) {
  const threshold = SEVERITY_ORDER.indexOf(MAX_SEVERITY_ALLOWED);
  const breaching = SEVERITY_ORDER
    .map((s, i) => ({ s, i, n: vulns[s] ?? 0 }))
    .filter((v) => v.i > threshold && v.n > 0);
  check(`no advisory above ${MAX_SEVERITY_ALLOWED} severity`, breaching.length === 0,
    breaching.length ? breaching.map((v) => `${v.n} ${v.s}`).join(', ')
      : SEVERITY_ORDER.map((s) => `${s}:${vulns[s] ?? 0}`).join(' '));
} else {
  // A scan that could not run is NOT a clean scan. Reporting it as passing would
  // be the precise inversion this platform exists to prevent.
  check('the vulnerability scan executed', false, 'audit produced no parseable result — treat as unscanned');
}

// ── 4. Dependency policy enforcement ────────────────────────────────────────
line('\n4. Dependency policy');
if (sbom) {
  const offending = sbom.components
    .map((c) => ({ name: c.name, id: c.licenses?.[0]?.license?.id ?? 'UNKNOWN' }))
    .filter((c) => !ALLOWED_LICENCES.has(c.id));
  check('every dependency licence is on the allow-list', offending.length === 0,
    offending.length ? offending.map((c) => `${c.name} (${c.id})`).join(', ')
      : `${sbom.components.length} component(s) within policy`);
}

// ── 5. Build reproducibility ────────────────────────────────────────────────
line('\n5. Build reproducibility');
function hashDist() {
  const dist = path.join(PKG, 'dist');
  if (!fs.existsSync(dist)) return null;
  const files = [];
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const full = path.join(d, e.name);
      if (e.isDirectory()) walk(full);
      // .tsbuildinfo records absolute paths and timestamps by design; excluding it
      // is a statement about what reproducibility means here, not a convenience.
      else if (e.isFile() && !e.name.endsWith('.tsbuildinfo')) files.push(full);
    }
  };
  walk(dist);
  files.sort();
  const h = crypto.createHash('sha256');
  for (const f of files) {
    h.update(path.relative(dist, f).split(path.sep).join('/'));
    h.update(fs.readFileSync(f));
  }
  return { hash: h.digest('hex'), count: files.length };
}

const build1 = pnpm(['-C', 'packages/contracts', 'build']);
const first = hashDist();
fs.rmSync(path.join(PKG, 'dist'), { recursive: true, force: true });
fs.rmSync(path.join(PKG, 'tsconfig.tsbuildinfo'), { force: true });
const build2 = pnpm(['-C', 'packages/contracts', 'build']);
const second = hashDist();

check('the package builds', build1.status === 0 && build2.status === 0,
  `first exit ${build1.status}, second exit ${build2.status}`);
check('two clean builds produce byte-identical output',
  first !== null && second !== null && first.hash === second.hash,
  first && second
    ? (first.hash === second.hash ? `${first.count} artefacts, sha256 ${first.hash.slice(0, 16)}…`
      : `differs: ${first.hash.slice(0, 12)} vs ${second.hash.slice(0, 12)}`)
    : 'dist absent after build');

// ── 6. What is NOT measured, and why ────────────────────────────────────────
line('\n6. Not measured');
notMeasured('artefact provenance attestation', 'no attestation tooling present; nothing is published to attest');
notMeasured('package signing verification', 'no signing tooling present; no package has been published');
notMeasured('trusted artefact promotion', 'no registry or promotion pipeline exists');

// ── Evidence ────────────────────────────────────────────────────────────────
const evidence = {
  evidenceId: 'supply-chain',
  generator: 'governance/verification/verify-supply-chain.js',
  generatorVersion: '1.0.0',
  executionContext: `node ${process.version} on ${process.platform}`,
  repository: 'DBiz_IntelligencePlane',
  commit: sbom ? (sbom.metadata.properties.find((p) => p.name === 'dbiz:commit')?.value ?? null) : null,
  adrReference: ['ADR-0011', 'ADR-0020'],
  ruleReference: ['R-22.6', 'R-22.8', 'R-22.9', 'R-22.10'],
  timestamp: new Date().toISOString(),
  measured,
  unmeasured,
  summary: {
    measuredTotal: measured.length,
    measuredPassed: measured.filter((m) => m.passed).length,
    unmeasuredTotal: unmeasured.length,
  },
  verificationStatus: failures === 0 ? 'verified' : 'failed',
  certificationStatus: failures === 0 ? 'partially-certified' : 'uncertified',
};
fs.writeFileSync(path.join(ROOT, 'governance', 'supply-chain', 'evidence.json'),
  `${JSON.stringify(evidence, null, 2)}\n`, 'utf8');

line('\n' + '='.repeat(74));
line(`${evidence.summary.measuredPassed}/${evidence.summary.measuredTotal} measured properties hold · ${unmeasured.length} NOT MEASURED`);
if (failures === 0) {
  line('RESULT: PASS — supply chain is PARTIALLY certified.');
  line('Signing, attestation and promotion remain unmeasured and are not claimed.');
} else {
  line(`RESULT: FAIL — ${failures} measured property violated.`);
}
line('');
process.exit(failures === 0 ? 0 : 1);
