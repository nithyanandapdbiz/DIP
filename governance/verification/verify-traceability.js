'use strict';
/**
 * GOVERNANCE — architecture coverage and enterprise traceability.
 * ============================================================================
 * Regenerates both matrices and gates on their evidence.
 *
 * WHY IT REGENERATES RATHER THAN READS.
 * Reading a committed matrix would gate on a historical claim — the file would
 * still assert full coverage long after a document was added with no owner. The
 * matrices are derived on every run, so a coverage gap appears the moment it is
 * created rather than the next time someone remembers to update a table (R-14.2).
 *
 * WHAT IT ENFORCES.
 *   1. Both matrices are regenerated by this run.
 *   2. Every architecture document has an implementation milestone.
 *   3. Every milestone claimed maps to a milestone the programme plan defines.
 *   4. Every Platform Service has canonical architecture.
 *   5. Every Quality Engineering Capability has canonical architecture.
 *   6. No criterion is cited in code without being declared in architecture.
 *   7. Unmeasured lifecycle stages are reported, not silently omitted.
 *
 * Property 3 is what stops the coverage map from being a way to make the matrix
 * green by pointing at nothing.
 *
 * Run:  node governance/verification/verify-traceability.js
 * Exit: 0 = coverage is complete   1 = an orphan or gap exists
 */
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.join(__dirname, '..', '..');
const GEN = path.join(ROOT, 'governance', 'traceability', 'generate-matrices.js');
const EVIDENCE = path.join(ROOT, 'governance', 'traceability', 'evidence.json');
const ARCH = path.join(ROOT, 'docs', 'architecture');

let failures = 0;
const line = (s) => console.log(s);
const check = (label, cond, detail) => {
  line(`  ${cond ? 'PASS ' : 'FAIL '} ${label}`);
  if (detail) line(`         ${detail}`);
  if (!cond) failures++;
};

const gateStartedAt = Date.now();
line('');
line('GOVERNANCE — architecture coverage and enterprise traceability');
line('='.repeat(74));

// ── 1. Regenerate ───────────────────────────────────────────────────────────
line('\n1. Matrix generation');
const gen = spawnSync(process.execPath, [GEN], { cwd: ROOT, encoding: 'utf8' });
check('the matrix generator ran cleanly', gen.status === 0,
  gen.status === 0 ? 'exit 0' : `exit ${gen.status}`);

let ev = null;
try { ev = JSON.parse(fs.readFileSync(EVIDENCE, 'utf8')); } catch { ev = null; }
check('matrix evidence is present and machine-readable', ev !== null,
  ev ? `${ev.coverage.documents} document(s), ${ev.chain.length} lifecycle stage(s)` : 'absent or unparseable');

if (!ev) {
  line('\n' + '='.repeat(74));
  line('RESULT: FAIL — traceability cannot be evidenced.');
  line('');
  process.exit(1);
}

const producedAt = Date.parse(ev.timestamp);
check('evidence was produced by this run, not left behind',
  Number.isFinite(producedAt) && producedAt >= gateStartedAt - 2000,
  Number.isFinite(producedAt) ? `produced ${Math.max(0, Math.round((Date.now() - producedAt) / 1000))}s ago` : 'no timestamp');

// ── 2. Architecture coverage ────────────────────────────────────────────────
line('\n2. Architecture coverage');
const o = ev.orphans ?? {};
check('every architecture document has an implementation milestone',
  (o.documentsWithoutMilestone ?? []).length === 0,
  (o.documentsWithoutMilestone ?? []).join(', ') || `${ev.coverage.documentsWithMilestone}/${ev.coverage.documents}`);

check('no coverage entry names a milestone the programme plan does not define',
  (o.phantomMilestones ?? []).length === 0,
  (o.phantomMilestones ?? []).join(', ') || 'every claimed milestone exists');

check('no criterion is cited in code without being declared in architecture',
  (o.criteriaCitedButUndeclared ?? []).length === 0,
  (o.criteriaCitedButUndeclared ?? []).join(', ') || 'implementation cites only declared criteria');

// ── 3. Platform Services and Capabilities have architecture ─────────────────
line('\n3. Canonical architecture exists where it must');
const present = fs.existsSync(ARCH) ? fs.readdirSync(ARCH) : [];
const has = (n) => present.some((f) => f.startsWith(`${n}-`));

const SERVICES = [['23', 'Operational Excellence'], ['24', 'Platform Intelligence'], ['25', 'Customer Success']];
const missingServices = SERVICES.filter(([n]) => !has(n)).map(([, t]) => t);
check('every Platform Service has canonical architecture', missingServices.length === 0,
  missingServices.join(', ') || SERVICES.map(([, t]) => t).join(', '));

const CAPABILITY_DOCS = [['11', 'capability model'], ['12', 'capability orchestration']];
const missingCapDocs = CAPABILITY_DOCS.filter(([n]) => !has(n)).map(([, t]) => t);
check('every Quality Engineering Capability has canonical architecture',
  missingCapDocs.length === 0,
  missingCapDocs.join(', ') || 'capability model and orchestration present');

// ── 4. Lifecycle chain ──────────────────────────────────────────────────────
line('\n4. Enterprise traceability chain');
const unmeasured = ev.chain.filter((s) => s.status === 'NOT MEASURED');
const populated = ev.chain.filter((s) => s.status !== 'NOT MEASURED');
line(`   ${populated.length}/${ev.chain.length} stages have artefacts`);
for (const s of unmeasured) line(`   NOT MEASURED  ${s.stage}`);

// Unmeasured stages are reported, never counted as failures. Release and customer
// deployment have no artefacts because nothing has been released or deployed —
// scoring that as a violation would penalise honesty about an unbuilt stage.
check('every lifecycle stage is either populated or explicitly unmeasured',
  ev.chain.every((s) => s.count > 0 || s.status === 'NOT MEASURED'),
  `${populated.length} populated, ${unmeasured.length} unmeasured and reported`);

// The chain must not be broken in the middle: an unmeasured stage BETWEEN two
// populated stages would mean evidence exists on both sides of a gap nobody can cross.
const firstUnmeasured = ev.chain.findIndex((s) => s.status === 'NOT MEASURED');
const lastPopulated = ev.chain.map((s) => s.status !== 'NOT MEASURED').lastIndexOf(true);
check('unmeasured stages are contiguous at the end of the chain, not gaps within it',
  firstUnmeasured === -1 || firstUnmeasured > lastPopulated,
  firstUnmeasured === -1 ? 'no unmeasured stages'
    : firstUnmeasured > lastPopulated
      ? `chain populated through stage ${lastPopulated + 1}, unmeasured thereafter`
      : `stage ${firstUnmeasured + 1} is unmeasured but later stages have artefacts — the chain is broken`);

check('the matrix generator verified its own output', ev.verificationStatus === 'verified',
  `verificationStatus=${ev.verificationStatus}`);

line('\n' + '='.repeat(74));
if (failures === 0) {
  line('RESULT: PASS — architecture coverage is complete and the chain is intact.');
} else {
  line(`RESULT: FAIL — ${failures} coverage or traceability property violated.`);
}
line('');
process.exit(failures === 0 ? 0 : 1);
